"""
프롬프트 템플릿과 꺼내오는 함수.

기능마다 두 개를 등록한다.
    <기능>_system   지시. 고정이라 데이터가 없다.
    <기능>_user     데이터. {} 자리에 값을 끼워 넣는다.

지시를 system 으로 분리하는 이유: 모델이 지시를 '따를 규칙'으로 다루고 데이터와
섞이지 않는다. 고정 부분과 변하는 부분이 갈려서 프롬프트 캐시도 잘 걸린다.
(ai-rag-comm 을 쓸 때는 system 역할이 없어서 한 덩어리로 합쳐야 했다.)

get_prompt(키, 데이터) 로 꺼내면 완성된 문자열이 나온다. 부르는 쪽은 템플릿이
어떻게 생겼는지 몰라도 된다.
"""

#------------------------------------------------┌> 축약어 사전 추출

# 규칙 하나하나가 실제로 관찰된 오류에 대응한다. 문서 하나를 두 모델로 뽑아 확인했다.
_VOCAB_SYSTEM = """\
너는 문서에서 축약어와 그 풀어쓴 말의 짝을 찾는다.

term 은 축약어(머리글자·줄임말), expansion 은 그것을 풀어쓴 이름이다.

무엇을 뽑는가
- 글에 풀어쓴 말이 실제로 적혀 있을 때만 뽑는다. 네가 아는 뜻으로 추론하지 마라.
- 그 문서·기관에서만 쓰는 용어를 뽑는다. 널리 쓰이는 일반 약어(AI, DS, XR, LMS 등)는
  뽑지 마라.
- expansion 은 원문이 그 축약어 바로 옆에 붙여 적은 정식 이름이어야 한다. 그 용어가
  속한 상위 분류나 일부만 옮긴 말은 안 된다.
    'Sol-Care -> 대학생활적응' 은 상위 분류다. '중도탈락 예방 프로그램' 이 정식 이름이다.
    'WTP -> 교수지원체계' 는 설명이다. 'Woosong Teaching Program' 이 정식 이름이다.
    'KOCW -> 공개강의' 는 일부만 옮긴 것이다.
- 하나의 축약어에 정식 이름이 여러 개 보이면 뜻이 다른 것만 항목을 나눈다.
  원문에 표기가 엇갈릴 때(오타 등)가 그런 경우다.
    'PAMS -> Partnership of Asia ...' 와 '... of Asian ...' 은 원문이 엇갈려서 둘 다 뽑는다.
- 대소문자나 띄어쓰기만 다른 표기는 하나만 뽑는다. 원문에 가장 많이 나온 형태를 쓴다.
    '7-Core' 와 '7-CORE' 는 하나만. '선이수프로그램' 과 '선이수 프로그램' 도 하나만.
- 하나도 없으면 빈 목록을 준다. 억지로 만들지 마라.

무엇을 뽑지 않는가
- term 과 expansion 이 같은 항목. '단기 -> 단기' 같은 것은 짝이 아니다.
- 한 글자 term(A, B, C, D, P)과 'B/A' 같은 계산 표시. 표의 열 이름이나 순환 단계
  표시이며 축약어가 아니다.
- 머리글자를 낱개로 쪼갠 항목. 'SMART -> Specific', 'SMART -> Measurable' 처럼
  글자마다 만들지 마라. 전체를 풀어쓴 하나만 뽑고, 그것도 나열·정의 문장이면 뽑지 마라.
- 설명·정의 문장을 expansion 에 넣은 항목. expansion 은 이름이어야 한다.
  '집중학기제 -> 현장실습 및 조기취업을 지원하는 제도' 는 설명이라 안 된다.

방향
- term 이 짧은 쪽(축약어), expansion 이 긴 쪽(풀어쓴 이름)이다. 뒤집지 마라.
  '선이수프로그램 -> Pre-College' 가 아니라 'Pre-College -> 선이수프로그램' 이다.
- 원문이 '핵심역량(7-Core)' 처럼 적혀 있으면 term='7-Core', expansion='핵심역량' 이다.
  expansion 에 괄호와 term 을 다시 넣지 마라."""

